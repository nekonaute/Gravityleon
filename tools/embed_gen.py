#!/usr/bin/env python3
# embed_gen.py OUT ROOT RESOURCE... : writes a C++ source (OUT) that bakes each RESOURCE -- a file,
# or every file under a directory -- into the binary, obfuscated, and defines embed_fopen(), the
# fopen() the "make dist" build uses (see src/embed.h). The key is a random keystream per build,
# written into the deobfuscator beside the bytes: it keeps the files out of `strings` and off a
# casual carver, no more -- the key ships in the binary, so it is obfuscation, not encryption.
#
# Each resource's lookup name is its path relative to ROOT with forward slashes -- exactly the
# string the game passes to fopen (it runs from its own folder: "data/params.txt", "levels/level 01.txt",
# "assets/music/03 - tno - Tartopom.mod", ...). Writes and any other path fall through to the real fopen.
import os, sys, random
from pathlib import Path

# These are the only save files shipped. Both packagers use the game's normal lookup names.
SCORE_NAMES = ("highscores.txt", "highscores_anna.txt")

def score_resources(root):
    return [("data/" + name, Path(root) / "data" / ("dist_" + name)) for name in SCORE_NAMES]

def collect(root, spec):
    if spec == "data":
        return score_resources(root)
    p = os.path.join(root, spec)
    if os.path.isdir(p):
        out = []
        for dirpath, _, names in os.walk(p):
            for n in sorted(names):
                if n.startswith('.'):
                    continue
                full = os.path.join(dirpath, n)
                out.append((os.path.relpath(full, root).replace(os.sep, '/'), full))
        return sorted(out)
    return [(spec.replace(os.sep, '/'), p)]

def main():
    if len(sys.argv) < 4:
        sys.exit("usage: embed_gen.py OUT ROOT RESOURCE...")
    out_path, root = sys.argv[1], sys.argv[2]
    items = []
    for spec in sys.argv[3:]:
        items += collect(root, spec)
    # drop duplicates, keep order
    seen, res = set(), []
    for name, full in items:
        if name not in seen:
            seen.add(name)
            res.append((name, full))

    seed = random.randint(0, 0xFFFFFFFF)
    def keyb(i):
        return (seed + i * 109 + (i >> 4) * 177 + 0x5A) & 0xFF

    lines = []
    lines.append("// GENERATED by tools/embed_gen.py for `make dist` -- do not edit, do not commit.")
    lines.append("#include <cstdio>")
    lines.append("#include <cstring>")
    lines.append("#include <cstdlib>")
    lines.append("#include <cerrno>")
    lines.append("#ifdef _WIN32")
    lines.append("#define WIN32_LEAN_AND_MEAN")
    lines.append("#include <windows.h>")
    lines.append("#endif")
    lines.append("#undef fopen   // the real libc fopen, for writes and non-embedded paths")
    lines.append("")
    lines.append("namespace {")
    lines.append("struct Res { const char* name; const unsigned char* data; unsigned long len; };")

    table = []
    for idx, (name, full) in enumerate(res):
        data = open(full, 'rb').read()
        obf = bytes(b ^ keyb(i) for i, b in enumerate(data))
        lines.append("static const unsigned char r%d[] = {" % idx)
        row = []
        chunk = []
        for j, b in enumerate(obf):
            chunk.append("%d," % b)
            if len(chunk) == 20:
                row.append("".join(chunk))
                chunk = []
        if chunk:
            row.append("".join(chunk))
        if not row:
            row.append("0")   # empty file: a 1-byte placeholder, len stays 0
        lines.append("\n".join(row))
        lines.append("};")
        esc = name.replace('\\', '\\\\').replace('"', '\\"')
        table.append('    { "%s", r%d, %dUL },' % (esc, idx, len(data)))

    lines.append("static const Res kRes[] = {")
    lines += table
    lines.append("};")
    lines.append("static const int kResN = %d;" % len(res))
    lines.append("static unsigned char* gCache[kResN ? kResN : 1];")
    lines.append("static const unsigned long kSeed = %dUL;" % seed)
    lines.append("static unsigned char keyb(unsigned long i) {")
    lines.append("    return (unsigned char)((kSeed + i * 109UL + (i >> 4) * 177UL + 0x5AUL) & 0xFFUL);")
    lines.append("}")
    lines.append("}  // namespace")
    lines.append("")
    lines.append("// A resource's index (-1: none); its bytes, decoded once and kept for the whole run (null: no memory).")
    lines.append("static int findRes(const char* path) {")
    lines.append("    if (path) for (int i = 0; i < kResN; i++) if (!strcmp(path, kRes[i].name)) return i;")
    lines.append("    return -1;")
    lines.append("}")
    lines.append("static unsigned char* cachedRes(int i) {")
    lines.append("    if (!gCache[i]) {")
    lines.append("        unsigned long n = kRes[i].len;")
    lines.append("        gCache[i] = (unsigned char*)malloc(n ? n : 1);")
    lines.append("        if (gCache[i]) for (unsigned long k = 0; k < n; k++) gCache[i][k] = kRes[i].data[k] ^ keyb(k);")
    lines.append("    }")
    lines.append("    return gCache[i];")
    lines.append("}")
    lines.append("")
    lines.append("extern \"C\" FILE* embed_fopen(const char* path, const char* mode) {")
    lines.append("    bool readonly = mode && !strpbrk(mode, \"wa+\");")
    lines.append("    int i = readonly ? findRes(path) : -1;")
    lines.append("    // Packaged highscores are defaults. Once a player saves, read their table from disk.")
    saved_paths = " || ".join(f'!strcmp(path, "data/{name}")' for name in SCORE_NAMES)
    lines.append(f"    if (i >= 0 && ({saved_paths})) {{")
    lines.append("        FILE* saved = fopen(path, mode);")
    lines.append("        if (saved || errno != ENOENT) return saved;")
    lines.append("    }")
    lines.append("    if (i >= 0 && cachedRes(i)) {")
    lines.append("#ifdef _WIN32")
    lines.append("        char directory[MAX_PATH], filename[MAX_PATH];")
    lines.append("        DWORD length = GetTempPathA(MAX_PATH, directory);")
    lines.append("        if (!length || length >= MAX_PATH || !GetTempFileNameA(directory, \"GL\", 0, filename)) {")
    lines.append("            errno = EIO;")
    lines.append("            return nullptr;")
    lines.append("        }")
    lines.append('        FILE* stream = fopen(filename, "w+bD"); // Delete on close.')
    lines.append("        if (!stream) {")
    lines.append("            int error = errno;")
    lines.append("            DeleteFileA(filename);")
    lines.append("            errno = error;")
    lines.append("            return nullptr;")
    lines.append("        }")
    lines.append("        size_t size = kRes[i].len;")
    lines.append("        if (fwrite(gCache[i], 1, size, stream) != size || fseek(stream, 0, SEEK_SET) != 0) {")
    lines.append("            int error = errno;")
    lines.append("            fclose(stream);")
    lines.append("            errno = error;")
    lines.append("            return nullptr;")
    lines.append("        }")
    lines.append("        return stream;")
    lines.append("#else")
    lines.append('        return fmemopen(gCache[i], kRes[i].len, "rb");')
    lines.append("#endif")
    lines.append("    }")
    lines.append("    return fopen(path, mode);")
    lines.append("}")
    lines.append("")
    lines.append("extern \"C\" const unsigned char* embed_data(const char* path, unsigned long* size) {")
    lines.append("    int i = findRes(path);")
    lines.append("    if (i < 0 || !cachedRes(i)) return nullptr;")
    lines.append("    if (size) *size = kRes[i].len;")
    lines.append("    return gCache[i];")
    lines.append("}")
    lines.append("")

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    open(out_path, "w").write("\n".join(lines))
    total = sum(os.path.getsize(f) for _, f in res)
    print("embed_gen: %d resource(s), %d bytes -> %s" % (len(res), total, out_path))
    for name, _ in res:
        print("  " + name)

if __name__ == "__main__":
    main()
